#!/usr/bin/env python3
"""Render or install the optional systemd frpc service (Python standard library only)."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import ssl
import subprocess
import sys
import tempfile

CONFIG_DIR = Path('/etc/tesla-sentry/frp')
BINARY = Path('/usr/local/lib/tesla-sentry/frpc')
UNIT = Path('/etc/systemd/system/tesla-sentry-frp.service')
CREDENTIAL_CA = '{{ .Envs.CREDENTIALS_DIRECTORY }}/ca.crt'

SERVICE = '''[Unit]
Description=Tesla Sentry tunnel to the user's cloud instance
Wants=network-online.target
After=network-online.target sentry-viewer.service
StartLimitIntervalSec=0

[Service]
Type=simple
DynamicUser=yes
LoadCredential=frpc.toml:/etc/tesla-sentry/frp/frpc.toml
LoadCredential=ca.crt:/etc/tesla-sentry/frp/ca.crt
ExecStart=/usr/local/lib/tesla-sentry/frpc -c ${CREDENTIALS_DIRECTORY}/frpc.toml
Restart=always
RestartSec=10
UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6
CapabilityBoundingSet=

[Install]
WantedBy=multi-user.target
'''


def parameters(raw):
    if not isinstance(raw, dict):
        raise ValueError('parameters must be a JSON object')
    required = {'server_addr', 'server_port', 'remote_port', 'device_id', 'token'}
    if not required <= raw.keys() or raw.keys() - required - {'local_port', 'server_name'}:
        raise ValueError('missing or unknown parameter fields')
    p = dict(raw)
    p.setdefault('local_port', 8080)
    p.setdefault('server_name', p['server_addr'])
    for key in ('server_addr', 'server_name'):
        if not isinstance(p[key], str) or not re.fullmatch(r'[A-Za-z0-9._:\-]+', p[key]):
            raise ValueError(key + ' must be a hostname or IP address, without a URL or port')
    if not isinstance(p['device_id'], str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', p['device_id']):
        raise ValueError('device_id must contain 1-64 letters, digits, underscores or hyphens')
    for key in ('server_port', 'remote_port', 'local_port'):
        if type(p[key]) is not int or not 1 <= p[key] <= 65535:
            raise ValueError(key + ' must be an integer between 1 and 65535')
    token = p['token']
    if not isinstance(token, str) or token.startswith('REPLACE_') or '{{' in token or len(token) < 32 or not token.isascii() or any(ord(c) < 33 or ord(c) > 126 for c in token):
        raise ValueError('token must contain at least 32 printable non-space ASCII characters')
    return p


def render(p, ca_path):
    q = json.dumps
    return f'''# Generated by configure_frp.py; contains credentials. Do not commit.
serverAddr = {q(p['server_addr'])}
serverPort = {p['server_port']}
loginFailExit = false
auth.method = "token"
auth.token = {q(p['token'])}
auth.additionalScopes = ["HeartBeats", "NewWorkConns"]
transport.protocol = "tcp"
transport.tls.enable = true
transport.tls.trustedCaFile = {q(str(ca_path))}
transport.tls.serverName = {q(p['server_name'])}
log.to = "console"
log.level = "warn"
log.disablePrintColor = true

[[proxies]]
name = {q('sentry-' + p['device_id'])}
type = "tcp"
localIP = "127.0.0.1"
localPort = {p['local_port']}
remotePort = {p['remote_port']}
'''


def write_atomic(path, data, mode):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as f:
            os.fchmod(f.fileno(), mode)
            f.write(data)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def check_binary(binary, config):
    # Never relay frpc output: a diagnostic may include the configuration's token.
    try:
        version = subprocess.run([str(binary), '--version'], capture_output=True, timeout=10, check=True)
        match = re.search(rb'\b(\d+)\.(\d+)\.(\d+)\b', version.stdout)
        if not match or tuple(map(int, match.groups())) < (0, 64, 0):
            raise ValueError('frpc >= 0.64.0 is required; use the same version as frps')
        env = dict(os.environ, CREDENTIALS_DIRECTORY=str(config.parent))
        subprocess.run([str(binary), 'verify', '-c', str(config)], capture_output=True, timeout=20, check=True, env=env)
    except (OSError, subprocess.SubprocessError):
        raise ValueError('frpc could not run or rejected the configuration; check binary architecture and version') from None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--parameters', required=True, type=Path, help='JSON file from the cloud or manual configuration')
    parser.add_argument('--ca', required=True, type=Path, help='trusted server CA certificate in PEM format')
    parser.add_argument('--output', type=Path, help='render to this directory without installing')
    parser.add_argument('--install', action='store_true', help='install and start the service (root, systemd >= 247)')
    parser.add_argument('--frpc', type=Path, help='trusted frpc executable for this device; required for installation')
    args = parser.parse_args(argv)
    if bool(args.output) == args.install:
        parser.error('choose exactly one of --output or --install')
    try:
        p = parameters(json.loads(args.parameters.read_text()))
        ca = args.ca.read_bytes()
        ssl.create_default_context(cadata=ca.decode('ascii'))
        if args.install:
            if os.geteuid() != 0 or not Path('/run/systemd/system').is_dir():
                raise ValueError('installation requires root on a running systemd host')
            if not args.frpc:
                raise ValueError('--frpc is required for installation')
            binary = args.frpc.resolve(strict=True)
            if not binary.is_file() or not os.access(binary, os.X_OK):
                raise ValueError('--frpc must be an executable file')
            if not shutil.which('systemctl'):
                raise ValueError('systemctl is not available')
            version = subprocess.run(['systemctl', '--version'], capture_output=True, check=True, timeout=10)
            match = re.match(rb'systemd (\d+)', version.stdout)
            if not match or int(match.group(1)) < 247:
                raise ValueError('systemd >= 247 is required for LoadCredential')
        with tempfile.TemporaryDirectory(prefix='tsf-frp-') as tmp:
            tmp = Path(tmp)
            write_atomic(tmp / 'ca.crt', ca, 0o644)
            ca_path = CREDENTIAL_CA if args.install else tmp / 'ca.crt'
            write_atomic(tmp / 'frpc.toml', render(p, ca_path).encode(), 0o600)
            if args.frpc:
                check_binary(args.frpc.resolve(), tmp / 'frpc.toml')
            if args.install:
                write_atomic(BINARY, binary.read_bytes(), 0o755)
                write_atomic(CONFIG_DIR / 'ca.crt', ca, 0o644)
                write_atomic(CONFIG_DIR / 'frpc.toml', render(p, CREDENTIAL_CA).encode(), 0o600)
                write_atomic(UNIT, SERVICE.encode(), 0o644)
                subprocess.run(['systemctl', 'daemon-reload'], check=True)
                subprocess.run(['systemctl', 'enable', UNIT.name], check=True)
                subprocess.run(['systemctl', 'restart', UNIT.name], check=True)
                print('Installed tesla-sentry-frp.service. Test the API from the cloud instance to confirm connectivity.')
            else:
                out = args.output.resolve()
                write_atomic(out / 'ca.crt', ca, 0o644)
                write_atomic(out / 'frpc.toml', render(p, out / 'ca.crt').encode(), 0o600)
                write_atomic(out / UNIT.name, SERVICE.encode(), 0o644)
                print('Rendered configuration only; the service template uses installation paths. No services changed.')
    except (ValueError, OSError, ssl.SSLError, subprocess.SubprocessError):
        # Do not print untrusted input or subprocess diagnostics containing secrets.
        print('Failed: check parameter fields, CA certificate, frpc compatibility and systemd prerequisites.', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
